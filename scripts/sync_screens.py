"""Generate ES module imports from numbered screen files; never import strategy code."""
import argparse
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def sync(check=False):
    folder=ROOT/'web/screens'
    paths=sorted(p for p in folder.glob('[0-9][0-9][0-9][0-9]-*.js') if p.is_file() and not p.is_symlink())
    if any(not re.fullmatch(r'[0-9]{4}-[a-z][a-z0-9-]*\.js',p.name) for p in paths):
        raise ValueError('Use NNNN-lowercase-screen-name.js')
    lines=['// Generated by scripts/sync_screens.py. Add numbered modules, then regenerate.']
    for i,path in enumerate(paths):lines.append(f"import screen{i} from './{path.name}';")
    lines+=['export const screenModules = ['+', '.join("{...screen"+str(i)+", source:'"+path.name+"'}" for i,path in enumerate(paths))+'];','']
    text='\n'.join(lines);target=folder/'catalog.js'
    if check:
        if not target.exists() or target.read_text()!=text:raise ValueError('Screen catalog is stale: run python scripts/sync_screens.py')
    else:target.write_text(text)
    return len(paths)

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();print(f'{sync(args.check)} screen modules')
