import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {paneContext} from '../web/pane-context.js';
import {context} from '../web/strategy-analysis.js';
import {marketLinkGroup} from '../web/charts/host.js';
import {performance,correlation} from '../web/analytics/statistics.js';
import {nativeRun} from './native-fixtures.mjs';
const a=nativeRun('a'),b=nativeRun('b');b.market[0].symbol='OTHER';
const report={account:null,runs:[a,b]},runtime={runs:[]},stored={prices:{STORED:[]},symbols:['STORED'],events:[],news:[],sources:[]};
const base={state:{nativeReport:report,runtime,symbol:'SYNTHETIC',mode:'persisted'},strategy:context(report,runtime,'a'),storedMarket:stored,marketSource:'run',actions:{}};
const left={},right={},screen={id:'performance',scope:'strategy',desk:'strategy'};
assert.equal(paneContext(base,left,screen).nativeRun.id,'a');
const changed={...base,strategy:context(report,runtime,'b')};
assert.equal(paneContext(changed,left,screen).nativeRun.id,'a','global defaults cannot change existing pane');
assert.equal(paneContext(changed,right,screen).nativeRun.id,'b');
left.followSelection=true;assert.equal(paneContext(changed,left,screen).nativeRun.id,'b');
left.followSelection=false;assert.equal(paneContext(changed,left,screen).nativeRun.id,'a');
const gp={id:'security',desk:'market'},p1={},p2={};
const m1=paneContext(base,p1,gp),m2=paneContext(changed,p2,gp);
assert.equal(m1.state.symbol,'SYNTHETIC');assert.equal(m2.state.symbol,'OTHER');
assert.notEqual(marketLinkGroup(m1),marketLinkGroup(m2));
assert.equal(paneContext({...changed,marketSource:'stored'},p1,gp).marketSource,'run');
p1.marketSource='stored';const storedCtx=paneContext(changed,p1,gp);assert.equal(storedCtx.state.symbol,'STORED');
storedCtx.actions.setFilter('search','private filter');assert.equal(p1.search,'private filter');assert.equal(p2.search,undefined);
assert.equal(storedCtx.state.data,stored);assert.equal(m1.market.events.length,0,'run bars cannot inherit current news');
assert.ok(Math.abs(performance(a.curve,1000).change-.002)<1e-12);assert.equal(correlation(a.curve,b.curve).value,null);
const source=readFileSync('web/analytics/statistics.js','utf8');assert.doesNotMatch(source,/\bimport\b|\bdocument\b|\bfetch\s*\(/);
console.log('Pane isolation passed: independent defaults, opt-in following, per-pane market/run/filter scope and pure statistics boundary.');
